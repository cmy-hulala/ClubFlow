export type MsgKey = keyof typeof zh;

const table: Record<Lang, typeof zh> = { zh, en };

export function t(lang: Lang, key: MsgKey): string {
  return table[lang][key];
}

export function tf(lang: Lang, key: MsgKey, vars: Record<string, string | number>): string {
  let text = t(lang, key);
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

